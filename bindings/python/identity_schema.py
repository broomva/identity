"""Validate one identity.v1 value against the generated schema.

Generated by scripts/generate_bindings.py. Do not edit.
"""

import json
import sys
from pathlib import Path

from jsonschema.validators import Draft202012Validator

SCHEMA = json.loads(Path(__file__).with_name("identity.v1.json").read_text())
VALIDATORS = {}


def validator(kind):
    cached = VALIDATORS.get(kind)
    if cached is not None:
        return cached
    if kind not in SCHEMA["$defs"]:
        raise KeyError(kind)
    compiled = Draft202012Validator(
        {
            "$schema": SCHEMA["$schema"],
            "$defs": SCHEMA["$defs"],
            "$ref": f"#/$defs/{kind}",
        }
    )
    VALIDATORS[kind] = compiled
    return compiled


def validate(kind, instance):
    """Return an error message, or None when the instance matches the schema."""
    try:
        compiled = validator(kind)
    except KeyError:
        return f"unknown kind {kind}"
    errors = sorted(compiled.iter_errors(instance), key=lambda error: list(error.absolute_path))
    if not errors:
        return None
    return errors[0].message


def main():
    document = json.loads(Path(sys.argv[1]).read_text())
    print("reject" if validate(document["kind"], document["value"]) else "accept")


if __name__ == "__main__":
    main()
